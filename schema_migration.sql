-- Harmonyapp Database Schema Migration Script (Fixed for Oracle / APEX)

-- 1. TABLES

-- Base Table for Contents
CREATE TABLE CONTENTS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(120) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    VISIBILITY VARCHAR2(20) DEFAULT 'PUBLIC' CHECK (VISIBILITY IN ('PUBLIC', 'PRIVATE', 'FOLLOWERS')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DELETED_AT TIMESTAMP
);

-- Users Table
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(80) NOT NULL,
    LAST_NAME VARCHAR2(80) NOT NULL,
    BIRTH_DATE DATE,
    USERNAME VARCHAR2(40) NOT NULL UNIQUE,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DELETED_AT TIMESTAMP
);

-- Profiles Table
CREATE TABLE PROFILES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    BIO VARCHAR2(160),
    AVATAR_URL VARCHAR2(500),
    USER_ID NUMBER NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DELETED_AT TIMESTAMP,
    CONSTRAINT FK_PROFILE_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Roles Table
CREATE TABLE ROLES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(40) NOT NULL UNIQUE
);

-- User Roles Join Table
CREATE TABLE USER_ROLES (
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID) ON DELETE CASCADE
);

-- Posts Table
CREATE TABLE POSTS (
    ID NUMBER PRIMARY KEY,
    AUDIO_URL VARCHAR2(500) NOT NULL,
    DURATION_SECONDS NUMBER,
    AUTHOR_ID NUMBER NOT NULL,
    PROFILE_ID NUMBER,
    CONSTRAINT FK_POST_CONTENT FOREIGN KEY (ID) REFERENCES CONTENTS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_POST_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_POST_PROFILE FOREIGN KEY (PROFILE_ID) REFERENCES PROFILES(ID) ON DELETE SET NULL
);

-- Tags Table
CREATE TABLE TAGS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    VALUE VARCHAR2(50) NOT NULL UNIQUE
);

-- Post Tags Join Table
CREATE TABLE POST_TAGS (
    POST_ID NUMBER NOT NULL,
    TAG_ID NUMBER NOT NULL,
    PRIMARY KEY (POST_ID, TAG_ID),
    CONSTRAINT FK_PT_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_PT_TAG FOREIGN KEY (TAG_ID) REFERENCES TAGS(ID) ON DELETE CASCADE
);

-- Comments Table
CREATE TABLE COMMENTS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    POST_ID NUMBER NOT NULL,
    AUTHOR_ID NUMBER NOT NULL,
    CONTENT VARCHAR2(280) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DELETED_AT TIMESTAMP,
    CONSTRAINT FK_COMMENT_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENT_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Groups Table
CREATE TABLE GROUPS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(80) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255),
    OWNER_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DELETED_AT TIMESTAMP,
    CONSTRAINT FK_GROUP_OWNER FOREIGN KEY (OWNER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Group Members Join Table
CREATE TABLE GROUP_MEMBERS (
    GROUP_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    PRIMARY KEY (GROUP_ID, USER_ID),
    CONSTRAINT FK_GM_GROUP FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_GM_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Group Join Requests Table
CREATE TABLE GROUP_JOIN_REQUESTS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    GROUP_ID NUMBER NOT NULL,
    REQUESTER_ID NUMBER NOT NULL,
    STATUS VARCHAR2(15) DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    MESSAGE VARCHAR2(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED NUMBER(1) DEFAULT 0 NOT NULL,
    DELETED_AT TIMESTAMP,
    CONSTRAINT FK_GJR_GROUP FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_GJR_REQUESTER FOREIGN KEY (REQUESTER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- 2. TRIGGERS

CREATE OR REPLACE TRIGGER TRG_USERS_UPDATED_AT
BEFORE UPDATE ON USERS
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
END;
/

